export const getRegionLabelRadio = (region: string, language: string): string => {
  const labels: Record<string, Record<string, string>> = {
    norway: { en: 'Norway', no: 'Norge', de: 'Norwegen' },
    nordic: { en: 'Nordic Countries', no: 'Norden', de: 'Nordische Länder' },
    world: { en: 'Worldwide', no: 'Verden', de: 'Weltweit' },
  };
  return labels[region]?.[language] ?? labels[region]?.['en'] ?? region;
};
